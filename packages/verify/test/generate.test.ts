import { describe, expect, test } from "bun:test";
import { z } from "zod";
import { GENERATOR_VERSION, generateCode, readGeneratedHeader } from "../src/registry/generate";
import { hashText } from "../src/registry/hash";
import { toOpenAPI } from "../src/registry/openapi";
import { billingTypes } from "./fixtures/billing";

const hash = "sha256-3q2+7w/Zm9vYmFy=";
const emptyDocument = { openapi: "3.1.0", info: { title: "x", version: "1.0.0" }, webhooks: {} };

function withComponents(schemas: Record<string, unknown>) {
  return { ...emptyDocument, components: { schemas } };
}

function schemaWithJson(json: unknown) {
  return { "~standard": { jsonSchema: { output: () => json } } };
}

function aliasNames(text: string): string[] {
  return [...text.matchAll(/^export type (\w+)[ <]/gm)].flatMap((match) => (match[1] ? [match[1]] : []));
}

describe("generateCode typescript", () => {
  test("writes the event map, the union, the helper, the factory and the header", async () => {
    const document = toOpenAPI(
      { "user.created": z.object({ userId: z.string(), nickname: z.string().nullable() }) },
      { title: "Accounts", version: "2.1.0" },
    );
    const body = [
      "",
      'import * as typedhook from "@typedhook/verify";',
      "",
      "export type UserAccountsEventMap = {",
      '  "user.created": {',
      '    event: "user.created";',
      "    subject: string | null;",
      "    data: {",
      "      userId: string;",
      "      nickname: string | null;",
      "    };",
      "  };",
      "};",
      "",
      "export type UserAccountsEvents = UserAccountsEventMap[keyof UserAccountsEventMap];",
      "",
      "export type UserAccountsEvent<K extends keyof UserAccountsEventMap> = UserAccountsEventMap[K];",
      "",
      '/** Verifies acme/user-accounts webhooks and routes them by "event". */',
      "export function createUserAccountsWebhooks(secret: string, options?: typedhook.WebhooksOptions) {",
      '  return typedhook.createWebhooks<UserAccountsEventMap>(secret, { ...options, discriminator: "event" });',
      "}",
      "",
    ].join("\n");
    const source = `acme/user-accounts@2.1.0 (doc ${hash}, body ${await hashText(body)})`;
    const header = `// Generated by typedhook pull v${GENERATOR_VERSION} from ${source}. Do not edit.`;
    expect(await generateCode("typescript", { registry: "acme/user-accounts", version: "2.1.0", hash, document })).toBe(
      `${header}\n${body}`,
    );
  });

  test("an empty webhooks object gives an empty map and no factory", async () => {
    const text = await generateCode("typescript", {
      registry: "acme/empty",
      version: "1.0.0",
      hash,
      document: emptyDocument,
    });
    expect(text).toContain("export type EmptyEventMap = Record<never, never>;");
    expect(text).not.toContain("createEmptyWebhooks");
  });

  test("rejects documents it can't read", async () => {
    await expect(
      generateCode("typescript", { registry: "acme/x", version: "1.0.0", hash, document: { openapi: "3.1.0" } }),
    ).rejects.toThrow("acme/x@1.0.0: the document has no webhooks object");
    const document = { webhooks: { "user.created": { post: {} } } };
    await expect(generateCode("typescript", { registry: "acme/x", version: "1.0.0", hash, document })).rejects.toThrow(
      'webhook "user.created" has no application/json request body',
    );
  });

  test("rejects a version, hash or registry that could break out of the header comment", async () => {
    const document = emptyDocument;
    for (const version of ["1.0.0\nexport const x = 1;", "1.0.0 x", "1.0.0 x", "v1.0.0", "1.0"]) {
      await expect(generateCode("typescript", { registry: "acme/x", version, hash, document })).rejects.toThrow(
        "acme/x: invalid version",
      );
    }
    for (const badHash of [`${hash}\nexport const x = 1;`, "sha256-", "md5-abc"]) {
      await expect(
        generateCode("typescript", { registry: "acme/x", version: "1.0.0", hash: badHash, document }),
      ).rejects.toThrow("acme/x@1.0.0: invalid hash");
    }
    await expect(
      generateCode("typescript", { registry: "acme/x\nexport const x = 1;", version: "1.0.0", hash, document }),
    ).rejects.toThrow("invalid registry");
  });

  test("prefixes component aliases with the registry name and keeps them unique", async () => {
    const text = await generateCode("typescript", {
      registry: "acme/polar",
      version: "1.0.0",
      hash,
      document: withComponents({
        "category.created": { type: "string" },
        "foo-bar": { type: "string" },
        foo_bar: { type: "number" },
        events: { type: "boolean" },
        event: { type: "null" },
        $: { type: "string" },
        "é": { type: "string" },
        "--": { type: "string" },
        record: { type: "string" },
      }),
    });
    expect(aliasNames(text)).toEqual([
      "PolarEventMap",
      "PolarEvents",
      "PolarEvent",
      "PolarSchema",
      "PolarSchema2",
      "PolarCategoryCreated",
      "PolarEvent2",
      "PolarEvents2",
      "PolarFooBar",
      "PolarFooBar2",
      "PolarRecord",
      "PolarSchema3",
    ]);
    expect(text).toContain("export type PolarEvent<K extends keyof PolarEventMap> = PolarEventMap[K];");
    expect(text).toContain("export type PolarFooBar2 = number;");
  });

  test("refs point at the renamed aliases, and unknown refs become unknown", async () => {
    const text = await generateCode("typescript", {
      registry: "acme/shop",
      version: "1.0.0",
      hash,
      document: withComponents({
        "a-b": { type: "array", items: { $ref: "#/components/schemas/a_b" } },
        a_b: { $ref: "#/components/schemas/a-b" },
        other: { $ref: "#/components/schemas/__proto__" },
      }),
    });
    expect(text).toContain("export type ShopAB = ShopAB2[];");
    expect(text).toContain("export type ShopAB2 = ShopAB;");
    expect(text).toContain("export type ShopOther = unknown;");
  });

  test("resolves component refs with escaped / and ~", async () => {
    const text = await generateCode("typescript", {
      registry: "acme/shop",
      version: "1.0.0",
      hash,
      document: withComponents({
        "a/b": { type: "string" },
        "c~d": { type: "number" },
        refs: {
          type: "array",
          prefixItems: [
            { $ref: "#/components/schemas/a~1b" },
            { $ref: "#/components/schemas/c~0d" },
            { $ref: "#/components/schemas/a~1b/items" },
          ],
          minItems: 3,
          items: false,
        },
      }),
    });
    expect(text).toContain("export type ShopRefs = [ShopAB, ShopCD, unknown];");
  });

  test("types recursive events and __proto__ names the way toOpenAPI wrote them", async () => {
    const tree = { type: "object", properties: { child: { $ref: "#" } } };
    const protoObject = JSON.parse(
      '{"type":"object","properties":{"__proto__":{"type":"string"}},"required":["__proto__"]}',
    );
    const events = Object.fromEntries([
      ["a/b", schemaWithJson(tree)],
      ["__proto__", schemaWithJson(protoObject)],
    ]);
    // Through JSON, like the document the registry returns.
    const document = JSON.parse(JSON.stringify(toOpenAPI(events, { title: "x", version: "1.0.0" })));
    const text = await generateCode("typescript", { registry: "acme/shop", version: "1.0.0", hash, document });
    expect(text).toContain('event: "a/b";\n    subject: string | null;\n    data: ShopAB;');
    expect(text).toContain("export type ShopAB = {\n  child?: ShopAB;\n};");
    expect(text).toContain('event: "__proto__";');
    expect(text).toContain("__proto__: string;");
  });

  test("names thousands of colliding components quickly", async () => {
    // 12,000 keys that all pascal-case to "X".
    const schemas = Object.fromEntries(
      Array.from({ length: 12_000 }, (_, index) => [
        `${"-".repeat(index % 110)}x${"-".repeat(Math.floor(index / 110))}`,
        { type: "string" },
      ]),
    );
    const startedAt = performance.now();
    const text = await generateCode("typescript", {
      registry: "acme/shop",
      version: "1.0.0",
      hash,
      document: withComponents(schemas),
    });
    expect(performance.now() - startedAt).toBeLessThan(500);
    expect(text).toContain("export type ShopX = string;");
    expect(text).toContain("export type ShopX12000 = string;");
  });

  test("refuses output past the size cap", async () => {
    const document = withComponents({ big: { enum: ["x".repeat(5_000_001)] } });
    await expect(generateCode("typescript", { registry: "acme/x", version: "1.0.0", hash, document })).rejects.toThrow(
      "over 5,000,000 characters",
    );
  });

  test("the committed billing fixture matches the generator", async () => {
    const committed = await Bun.file(new URL("./fixtures/billing-events.ts", import.meta.url)).text();
    // On failure, regenerate with `bun packages/verify/test/fixtures/billing.ts` and review the diff.
    expect(await billingTypes()).toBe(committed);
  });
});

describe("readGeneratedHeader", () => {
  test("reads back what generateCode wrote", async () => {
    const text = await generateCode("typescript", {
      registry: "acme/empty",
      version: "1.0.0",
      hash,
      document: emptyDocument,
    });
    const header = readGeneratedHeader(text);
    expect(header).toEqual({
      generatorVersion: GENERATOR_VERSION,
      registry: "acme/empty",
      version: "1.0.0",
      documentHash: hash,
      bodyHash: expect.stringMatching(/^sha256-/),
      body: text.slice(text.indexOf("\n") + 1),
    });
    expect(await hashText(header?.body ?? "")).toBe(header?.bodyHash ?? "");
  });

  test("reads a CRLF checkout as the LF file it was written as", async () => {
    const text = await generateCode("typescript", {
      registry: "acme/empty",
      version: "1.0.0",
      hash,
      document: emptyDocument,
    });
    expect(readGeneratedHeader(text.replaceAll("\n", "\r\n"))).toEqual(readGeneratedHeader(text));
  });

  test("returns null for files it didn't generate", () => {
    expect(readGeneratedHeader("export type Mine = string;\n")).toBeNull();
    expect(readGeneratedHeader(`// hand-written (${hash})\n`)).toBeNull();
    const oldFormat = `// Generated by \`typedhook pull\` from acme/x@1.0.0 (${hash}). Do not edit.\n`;
    expect(readGeneratedHeader(oldFormat)).toBeNull();
    expect(readGeneratedHeader("")).toBeNull();
  });
});

describe("generateCode typescript for any payload shape", () => {
  test("keys the map by the discriminator's value and documents events and fields", async () => {
    const document = {
      openapi: "3.1.0",
      info: { title: "Stripe", version: "1.0.0" },
      webhooks: {
        InvoicePaid: {
          post: {
            summary: "Sent when an invoice is paid. */ export const pwned = 1; /*",
            requestBody: {
              content: {
                "application/json": {
                  schema: {
                    type: "object",
                    properties: {
                      type: { const: "invoice.paid" },
                      amount: { type: "integer", description: "In cents\nnever negative" },
                    },
                    required: ["type", "amount"],
                  },
                },
              },
            },
          },
        },
      },
    };
    const text = await generateCode("typescript", { registry: "acme/stripe", version: "1.0.0", hash, document });
    expect(text).toContain(
      [
        "export type StripeEventMap = {",
        "  /** Sent when an invoice is paid. *\\/ export const pwned = 1; /* */",
        '  "invoice.paid": {',
        '    type: "invoice.paid";',
        "    /**",
        "     * In cents",
        "     * never negative",
        "     */",
        "    amount: number;",
        "  };",
        "};",
      ].join("\n"),
    );
    expect(text).toContain('{ ...options, discriminator: "type" }');
    expect(text).not.toMatch(/^export const pwned/m);
  });

  test("events that don't carry their name get types but no factory", async () => {
    const payload = (properties: Record<string, unknown>) => ({
      post: { requestBody: { content: { "application/json": { schema: { type: "object", properties } } } } },
    });
    const document = {
      openapi: "3.1.0",
      info: { title: "GitHub", version: "1.0.0" },
      webhooks: { push: payload({ ref: { type: "string" } }), star: payload({ starred_at: { type: "string" } }) },
    };
    const text = await generateCode("typescript", { registry: "acme/github", version: "1.0.0", hash, document });
    expect(text).toContain('  "push": {\n    ref?: string;\n  };');
    expect(text).not.toContain("import * as typedhook");
    expect(text).not.toContain("createGithubWebhooks");
  });

  test("a hostile discriminator stays inside its string", async () => {
    const property = '"; } export const pwned = 1; /*\n*/';
    const document = {
      openapi: "3.1.0",
      info: { title: "x", version: "1.0.0" },
      webhooks: {
        a: {
          post: {
            requestBody: {
              content: { "application/json": { schema: { type: "object", properties: { [property]: { const: "a" } } } } },
            },
          },
        },
      },
    };
    const text = await generateCode("typescript", { registry: "acme/x", version: "1.0.0", hash, document });
    expect(text).not.toMatch(/^export const pwned/m);
    expect(text).toContain(`discriminator: ${JSON.stringify(property)} });`);
  });
});
