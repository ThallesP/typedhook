// The Standard Webhooks signer: HMAC-SHA256 over `{id}.{timestamp}.{body}`.
function sign(key: Uint8Array | string, id: string, timestamp: string | number, body: string): string {
  return `v1,${createHmac("sha256", key).update(`${id}.${timestamp}.`).update(body).digest("base64")}`;
}

type VerifyCase = {
  name: string;
  body: string;
  headers: Record<string, string>;
  secret: string;
  isBytes?: boolean;
  isCaseInsensitive?: boolean;
  toleranceSec?: number;
  expected: Outcome;
};

type Outcome = { event: unknown } | { reason: string } | { error: "config" };

async function verifyWithTypeScript(verifyCase: VerifyCase): Promise<Outcome> {
  const { body, headers, secret, isBytes, isCaseInsensitive, toleranceSec } = verifyCase;
  try {
    const verifier = createVerifier(secret, { toleranceSec });
    const result = await verifier.verifyPayload(
      isBytes ? encoder.encode(body) : body,
      isCaseInsensitive ? new Headers(headers) : headers,
    );
    return result.ok ? { event: result.payload } : { reason: result.reason };
  } catch (error) {
    // createVerifier throws once, where Python's verify() raises on every call.
    if (error instanceof RangeError && error.message.includes("secret")) return { reason: "invalid_secret" };
    return { error: "config" };
  }
}

const runner = `
import json
import sys
from collections.abc import Mapping

import billing


class Headers(Mapping[str, str]):
    """Case-insensitive, like Django's and Starlette's request headers."""

    def __init__(self, items: dict[str, str]) -> None:
        self._items = {key.lower(): value for key, value in items.items()}

    def __getitem__(self, key: str) -> str:
        return self._items[key.lower()]

    def __iter__(self):
        return iter(self._items)

    def __len__(self) -> int:
        return len(self._items)


results = []
for case in json.load(open(sys.argv[1])):
    payload = case["body"].encode() if case.get("isBytes") else case["body"]
    headers = Headers(case["headers"]) if case.get("isCaseInsensitive") else case["headers"]
    options = {} if case.get("toleranceSec") is None else {"tolerance_sec": case["toleranceSec"]}
    try:
        results.append({"event": billing.verify(payload, headers, case["secret"], **options)})
    except billing.WebhookVerificationError as error:
        results.append({"reason": error.reason})
    except ValueError:
        results.append({"error": "config"})
print(json.dumps(results))
`;

