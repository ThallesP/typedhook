function withComponents(schemas: Record<string, unknown>) {
  return { ...emptyDocument, components: { schemas } };
}

function webhook(schema: unknown, summary?: string) {
  return { post: { summary, requestBody: { content: { "application/json": { schema } } } } };
}

function withEvents(webhooks: Record<string, unknown>, schemas: Record<string, unknown> = {}) {
  return { ...emptyDocument, webhooks, components: { schemas } };
}

function schemaWithJson(json: unknown) {
  return { "~standard": { jsonSchema: { output: () => json } } };
}

function definitionNames(text: string): string[] {
  return [...text.matchAll(/^(?:class (\w+)\(|(\w+)(?:: TypeAlias)? = )/gm)].flatMap((match) => {
    const name = match[1] ?? match[2];
    return name === undefined ? [] : [name];
  });
}

/**
 * Top-level comments other than `#:` descriptions: what mypy reads `# mypy:`
 * config from. (Indented `#` lines can be docstring text.)
 */
function plainComments(text: string): string[] {
  return text.split("\n").filter((line) => /^#(?!:)/.test(line) && !line.startsWith("# Generated by"));
}

function maxBracketDepth(line: string): number {
  let depth = 0;
  let max = 0;
  for (const char of line) {
    if (char === "[") max = Math.max(max, ++depth);
    if (char === "]") depth--;
  }
  return max;
}

