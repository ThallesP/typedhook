import { componentName } from "./component-ref";
import { hashText, isHash } from "./hash";
import { isRecord } from "./is-record";
import { MAX_OUTPUT_LENGTH, jsonSchemaToTs } from "./json-schema-to-ts";
import { isStrictSemver, parseRegistry } from "./registry-client";

/** Bump whenever generateTypes output changes, so `pull` regenerates files written by older versions. */
export const GENERATOR_VERSION = 2;

export type GenerateTypesInput = {
  /** `owner/name` */
  registry: string;
  version: string;
  hash: string;
  document: unknown;
};

export type GeneratedHeader = {
  generatorVersion: number;
  registry: string;
  version: string;
  /** Hash of the registry document the file was generated from. */
  documentHash: string;
  /** Hash of `body`, as written. */
  bodyHash: string;
  /** Everything after the header line. */
  body: string;
};

const HEADER =
  /^\/\/ Generated by typedhook pull v(\d+) from ([^\s@]+)@(\S+) \(doc (sha256-[A-Za-z0-9+/]+={0,2}), body (sha256-[A-Za-z0-9+/]+={0,2})\)\. Do not edit\.\n/;

/**
 * File text for one registry: a `<Name>Events` union keyed by `event`, a
 * `<Name>Event<K>` helper, and one alias per component schema (recursive
 * types need a name to point back to).
 */
export async function generateTypes({
  registry,
  version,
  hash,
  document,
}: GenerateTypesInput): Promise<string> {
  // All three go into the header comment; a newline in any of them would end it.
  const { name } = parseRegistry(registry);
  if (!isStrictSemver(version)) throw new Error(`${registry}: invalid version ${JSON.stringify(version)}`);
  if (!isHash(hash)) throw new Error(`${registry}@${version}: invalid hash ${JSON.stringify(hash)}`);
  if (!isRecord(document) || !isRecord(document.webhooks)) {
    throw new Error(`${registry}@${version}: the document has no webhooks object`);
  }
  const { webhooks } = document;
  const schemas =
    isRecord(document.components) && isRecord(document.components.schemas)
      ? document.components.schemas
      : {};

  const base = typeName(name);
  const eventsName = `${base}Events`;
  const eventName = `${base}Event`;
  // Component names are prefixed with the registry's so they can't shadow the
  // built-ins the file uses; the reserved ones stay taken anyway.
  const names = uniqueNames([eventsName, eventName, "Record", "Extract"]);
  const aliases = new Map(
    Object.keys(schemas)
      .sort()
      .map((key) => [key, names.claim(`${base}${pascalCase(key) || "Schema"}`)]),
  );
  const refName = (ref: string) => {
    const key = componentName(ref);
    return key === null ? undefined : aliases.get(key);
  };

  const members = Object.keys(webhooks)
    .sort()
    .map((event) => eventMember(event, eventData(event, webhooks[event]), refName));
  const union = members.length > 0 ? `\n${members.join("\n")}` : " never";

  const lines = [
    "",
    `export type ${eventsName} =${union};`,
    "",
    `export type ${eventName}<K extends ${eventsName}["event"]> = Extract<${eventsName}, { event: K }>;`,
  ];
  for (const [key, alias] of aliases) {
    lines.push("", `export type ${alias} = ${jsonSchemaToTs(schemas[key], { refName })};`);
  }
  const body = `${lines.join("\n")}\n`;
  if (body.length > MAX_OUTPUT_LENGTH) {
    throw new Error(
      `${registry}@${version}: the types would be over ${MAX_OUTPUT_LENGTH.toLocaleString("en-US")} characters`,
    );
  }
  const source = `${registry}@${version} (doc ${hash}, body ${await hashText(body)})`;
  return `// Generated by typedhook pull v${GENERATOR_VERSION} from ${source}. Do not edit.\n${body}`;
}

/** The header generateTypes wrote, or null when the text isn't a generated file. */
export function readGeneratedHeader(text: string): GeneratedHeader | null {
  // Git checks the file out with CRLF under core.autocrlf; that's not an edit.
  const lf = text.replaceAll("\r\n", "\n");
  const match = HEADER.exec(lf);
  if (!match) return null;
  const [header, generatorVersion, registry, version, documentHash, bodyHash] = match;
  return {
    generatorVersion: Number(generatorVersion),
    registry,
    version,
    documentHash,
    bodyHash,
    body: lf.slice(header.length),
  };
}

function eventData(name: string, webhook: unknown): unknown {
  const data = getPath(webhook, [
    "post",
    "requestBody",
    "content",
    "application/json",
    "schema",
    "properties",
    "data",
  ]);
  if (data === undefined) throw new Error(`webhook "${name}" has no request body with a data property`);
  return data;
}

function eventMember(
  name: string,
  data: unknown,
  refName: (ref: string) => string | undefined,
): string {
  return [
    "  | {",
    `      event: ${JSON.stringify(name)};`,
    "      subject: string | null;",
    `      data: ${jsonSchemaToTs(data, { refName, indent: 3 })};`,
    "    }",
  ].join("\n");
}

function getPath(value: unknown, keys: string[]): unknown {
  let current = value;
  for (const key of keys) {
    if (!isRecord(current)) return undefined;
    current = current[key];
  }
  return current;
}

/**
 * `claim(name)` is `name`, or `name2`, `name3`, ... when it's taken, and marks
 * the result taken. Remembers each name's next suffix, so thousands of
 * colliding names don't rescan from 2 every time.
 */
function uniqueNames(reserved: string[]): { claim: (name: string) => string } {
  const taken = new Set(reserved);
  const nextSuffix = new Map<string, number>();
  function claim(name: string): string {
    let unique = name;
    let suffix = nextSuffix.get(name) ?? 2;
    while (taken.has(unique)) unique = `${name}${suffix++}`;
    nextSuffix.set(name, suffix);
    taken.add(unique);
    return unique;
  }
  return { claim };
}

function typeName(text: string): string {
  const name = pascalCase(text);
  return /^\d/.test(name) ? `_${name}` : name;
}

function pascalCase(text: string): string {
  return text
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
}
