import { isHash, hashText } from "./hash";
import { MAX_OUTPUT_LENGTH } from "./json-schema-to-ts";
import { type RegistryModel, readRegistryDocument } from "./model";
import { goPackageName, pythonModuleName } from "./names";
import { isStrictSemver, parseRegistry } from "./registry-client";
import { goCode } from "./go";
import { pythonCode } from "./python";
import { typescriptCode } from "./typescript";

/** Bump whenever generated output changes, so `pull` regenerates files written by older versions. */
export const GENERATOR_VERSION = 3;

export const LANGS = ["typescript", "python", "go"] as const;

export type Lang = (typeof LANGS)[number];

export type GenerateInput = {
  /** `owner/name` */
  registry: string;
  version: string;
  hash: string;
  document: unknown;
};

/** What a language's generator gets: the parsed document plus where it came from. */
export type CodegenContext = {
  registry: string;
  owner: string;
  name: string;
  version: string;
  model: RegistryModel;
};

export type GeneratedHeader = {
  generatorVersion: number;
  registry: string;
  version: string;
  /** Hash of the registry document the file was generated from. */
  documentHash: string;
  /** Hash of `body`, as written. */
  bodyHash: string;
  /** Everything after the header line. */
  body: string;
};

const generators: Record<Lang, (context: CodegenContext) => string> = {
  typescript: typescriptCode,
  python: pythonCode,
  go: goCode,
};

// Go tooling only treats a file as generated when its first line matches
// `^// Code generated .* DO NOT EDIT\.$`.
const headerLines: Record<Lang, (source: string) => string> = {
  typescript: (source) => `// Generated by typedhook pull v${GENERATOR_VERSION} from ${source}. Do not edit.`,
  python: (source) => `# Generated by typedhook pull v${GENERATOR_VERSION} from ${source}. Do not edit.`,
  go: (source) => `// Code generated by typedhook pull v${GENERATOR_VERSION} from ${source}. DO NOT EDIT.`,
};

const HEADER =
  /^(?:\/\/|#) (?:Code generated|Generated) by typedhook pull v(\d+) from ([^\s@]+)@(\S+) \(doc (sha256-[A-Za-z0-9+/]+={0,2}), body (sha256-[A-Za-z0-9+/]+={0,2})\)\. (?:Do not edit|DO NOT EDIT)\.\n/;

const fileNames: Record<Lang, (name: string) => string> = {
  typescript: (name) => `${name}.ts`,
  python: (name) => `${pythonModuleName(name)}.py`,
  go: (name) => `${goPackageName(name)}/${goPackageName(name)}.go`,
};

/** Where `typedhook pull` writes a registry's code, relative to the output directory. */
export function generatedFileName(lang: Lang, name: string): string {
  return fileNames[lang](name);
}

// A Map, so `constructor` doesn't find Object.prototype members.
const langAliases = new Map<string, Lang>([
  ["typescript", "typescript"],
  ["ts", "typescript"],
  ["python", "python"],
  ["py", "python"],
  ["go", "go"],
  ["golang", "go"],
]);

export function findLang(text: string): Lang | null {
  return langAliases.get(text.toLowerCase()) ?? null;
}

export function parseLang(text: string): Lang {
  const lang = findLang(text);
  if (lang === null) throw new Error(`unknown language "${text}", expected one of ${LANGS.join(", ")}`);
  return lang;
}

/** The registry document parsed for generators, after checking what goes into headers. */
export function codegenContext({ registry, version, hash, document }: GenerateInput): CodegenContext {
  // All three go into the header comment; a newline in any of them would end it.
  const { owner, name } = parseRegistry(registry);
  if (!isStrictSemver(version)) throw new Error(`${registry}: invalid version ${JSON.stringify(version)}`);
  if (!isHash(hash)) throw new Error(`${registry}@${version}: invalid hash ${JSON.stringify(hash)}`);
  const model = readRegistryDocument(`${registry}@${version}`, document);
  return { registry, owner, name, version, model };
}

/** The file `typedhook pull` writes for one registry in `lang`, header included. */
export async function generateCode(lang: Lang, input: GenerateInput): Promise<string> {
  const context = codegenContext(input);
  const body = generators[lang](context);
  if (body.length > MAX_OUTPUT_LENGTH) {
    throw new Error(
      `${input.registry}@${input.version}: the code would be over ${MAX_OUTPUT_LENGTH.toLocaleString("en-US")} characters`,
    );
  }
  const source = `${input.registry}@${input.version} (doc ${input.hash}, body ${await hashText(body)})`;
  return `${headerLines[lang](source)}\n${body}`;
}

/** The header generateCode wrote, or null when the text isn't a generated file. */
export function readGeneratedHeader(text: string): GeneratedHeader | null {
  // Git checks the file out with CRLF under core.autocrlf; that's not an edit.
  const lf = text.replaceAll("\r\n", "\n");
  const match = HEADER.exec(lf);
  if (!match) return null;
  const [header, generatorVersion, registry, version, documentHash, bodyHash] = match;
  return {
    generatorVersion: Number(generatorVersion),
    registry,
    version,
    documentHash,
    bodyHash,
    body: lf.slice(header.length),
  };
}
