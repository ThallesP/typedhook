import { type GenerateInput, type Lang, codegenContext, generateCode } from "./generate";
import { goName } from "./go";
import { isRecord } from "./is-record";
import { getDescription } from "./json-schema-to-ts";
import { type RegistryModel, eventKey } from "./model";
import { goPackageName, pythonModuleName, typeName } from "./names";

/** The @typedhook/verify releases generated TypeScript packages work with; bump with breaking releases. */
const VERIFY_RANGE = "^0.3.0";

export type SdkOptions = {
  /** npm or PyPI package name, or the Go module path. */
  packageName?: string;
  /** Shown in the README; the document's title when unset. */
  title?: string;
};

export type SdkPackage = {
  packageName: string;
  /** Relative path → content. */
  files: Map<string, string>;
};

type PackageContext = {
  input: GenerateInput;
  owner: string;
  name: string;
  title: string;
  model: RegistryModel;
  packageName: string;
  code: string;
};

const defaultPackageNames: Record<Lang, (owner: string, name: string) => string> = {
  typescript: (owner, name) => `@${owner}/${name}-webhooks`,
  python: (owner, name) => `${owner}-${name}-webhooks`,
  go: (owner, name) => `github.com/${owner}/${name}-webhooks-go`,
};

const packagers: Record<Lang, (context: PackageContext) => Map<string, string>> = {
  typescript: typescriptPackage,
  python: pythonPackage,
  go: goPackage,
};

/**
 * A package a sender publishes under their own name (the Stainless way): the
 * generated code plus a manifest, a README listing every event, and nothing
 * to configure.
 */
export async function generatePackage(lang: Lang, input: GenerateInput, options: SdkOptions = {}): Promise<SdkPackage> {
  const { owner, name, model } = codegenContext(input);
  const packageName = options.packageName ?? defaultPackageNames[lang](owner, name);
  const title = options.title ?? documentTitle(input.document) ?? name;
  const code = await generateCode(lang, input);
  return { packageName, files: packagers[lang]({ input, owner, name, title, model, packageName, code }) };
}

function typescriptPackage({ input, name, title, model, packageName, code }: PackageContext): Map<string, string> {
  const packageJson = {
    name: packageName,
    version: input.version,
    description: `Typed webhooks for ${title}, generated by typedhook`,
    type: "module",
    main: "./dist/index.js",
    types: "./dist/index.d.ts",
    exports: { ".": { types: "./dist/index.d.ts", import: "./dist/index.js" } },
    files: ["dist"],
    scripts: { build: "tsc", prepublishOnly: "tsc" },
    dependencies: { "@typedhook/verify": VERIFY_RANGE },
    devDependencies: { typescript: "^5.7.0" },
  };
  const tsconfig = {
    compilerOptions: {
      target: "ES2022",
      module: "NodeNext",
      moduleResolution: "NodeNext",
      declaration: true,
      outDir: "dist",
      strict: true,
      skipLibCheck: true,
    },
    include: ["src"],
  };
  const base = typeName(name);
  const usage = model.discriminator
    ? [
        `import { create${base}Webhooks } from "${packageName}";`,
        "",
        `const webhooks = create${base}Webhooks(process.env.WEBHOOK_SECRET!);`,
        "",
        "// Next.js, Hono, Remix, Workers, Bun",
        "export const POST = webhooks.handler({",
        `  ${JSON.stringify(firstKey(model))}: async (payload) => {`,
        "    // payload is typed for this event",
        "  },",
        "});",
      ]
    : [
        'import { createVerifier } from "@typedhook/verify";',
        `import type { ${base}Events } from "${packageName}";`,
        "",
        "const verifier = createVerifier(process.env.WEBHOOK_SECRET!);",
        `const result = await verifier.verify<${base}Events>(request);`,
      ];
  return new Map([
    ["package.json", `${JSON.stringify(packageJson, null, 2)}\n`],
    ["tsconfig.json", `${JSON.stringify(tsconfig, null, 2)}\n`],
    ["src/index.ts", code],
    ["README.md", readme({ title, input, model, install: `npm install ${packageName}`, lang: "ts", usage })],
  ]);
}

function pythonPackage({ input, name, title, model, packageName, code }: PackageContext): Map<string, string> {
  const module = pythonModuleName(packageName);
  const pyproject = [
    "[build-system]",
    'requires = ["hatchling"]',
    'build-backend = "hatchling.build"',
    "",
    "[project]",
    `name = ${JSON.stringify(packageName)}`,
    `version = ${JSON.stringify(input.version)}`,
    `description = ${JSON.stringify(`Typed webhooks for ${title}, generated by typedhook`)}`,
    'readme = "README.md"',
    'requires-python = ">=3.9"',
    "dependencies = ['typing_extensions>=4.0; python_version < \"3.11\"']",
    "",
    "[tool.hatch.build.targets.wheel]",
    `packages = [${JSON.stringify(`src/${module}`)}]`,
    "",
  ].join("\n");
  const key = firstKey(model);
  const usage = [
    `from ${module} import WebhookVerificationError, verify`,
    "",
    "try:",
    "    event = verify(request.body, request.headers, WEBHOOK_SECRET)",
    "except WebhookVerificationError as error:",
    "    return Response(error.reason, status=400)",
    ...(model.discriminator
      ? [`if event[${JSON.stringify(model.discriminator.property)}] == ${JSON.stringify(key)}:`, "    ...  # event is typed for this event"]
      : []),
  ];
  return new Map([
    ["pyproject.toml", pyproject],
    [`src/${module}/__init__.py`, code],
    [`src/${module}/py.typed`, ""],
    ["README.md", readme({ title, input, model, install: `pip install ${packageName}`, lang: "python", usage })],
  ]);
}

function goPackage({ input, name, title, model, packageName, code }: PackageContext): Map<string, string> {
  const pkg = goPackageName(name);
  const usage = [
    `import ${pkg} "${packageName}"`,
    "",
    "func handle(w http.ResponseWriter, r *http.Request) {",
    "\tbody, _ := io.ReadAll(r.Body)",
    model.discriminator
      ? `\tevent, err := ${pkg}.Verify(body, r.Header, os.Getenv("WEBHOOK_SECRET"))`
      : `\terr := ${pkg}.VerifySignature(body, r.Header, os.Getenv("WEBHOOK_SECRET"))`,
    "\tif err != nil {",
    "\t\thttp.Error(w, err.Error(), http.StatusBadRequest)",
    "\t\treturn",
    "\t}",
    ...(model.discriminator
      ? ["\tswitch event := event.(type) {", `\tcase *${pkg}.${goTypeHint(model)}:`, "\t\t_ = event // typed for this event", "\t}"]
      : []),
    "\tw.WriteHeader(http.StatusNoContent)",
    "}",
  ];
  return new Map([
    ["go.mod", `module ${packageName}\n\ngo 1.21\n`],
    [`${pkg}.go`, code],
    ["README.md", readme({ title, input, model, install: `go get ${packageName}`, lang: "go", usage })],
  ]);
}

function readme({
  title,
  input,
  model,
  install,
  lang,
  usage,
}: {
  title: string;
  input: GenerateInput;
  model: RegistryModel;
  install: string;
  lang: string;
  usage: string[];
}): string {
  const rows = model.events.map((event) => {
    const description = event.description ?? getDescription(event.payload) ?? "";
    return `| \`${eventKey(model, event).replaceAll("|", "\\|")}\` | ${oneLine(description)} |`;
  });
  return [
    `# ${oneLine(title)} webhooks`,
    "",
    `Typed payloads and signature verification for the webhooks ${oneLine(title)} sends. Generated by [typedhook](https://typedhook.dev) from \`${input.registry}@${input.version}\`.`,
    "",
    "## Install",
    "",
    "```sh",
    install,
    "```",
    "",
    "## Usage",
    "",
    `\`\`\`${lang}`,
    ...usage,
    "```",
    "",
    "Signatures follow [Standard Webhooks](https://www.standardwebhooks.com/). Webhooks can arrive more than once: store the delivery id and skip ids you've seen.",
    "",
    "## Events",
    "",
    "| Event | Description |",
    "| --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

function firstKey(model: RegistryModel): string {
  const [first] = model.events;
  return first ? eventKey(model, first) : "event.name";
}

/** The Go struct the first event decodes into, named the way the generator names it. */
function goTypeHint(model: RegistryModel): string {
  const [first] = model.events;
  return first ? goName(first.name, "Event") : "Event";
}

function oneLine(text: string): string {
  return text.replaceAll(/\s+/g, " ").replaceAll("|", "\\|").trim();
}

function documentTitle(document: unknown): string | null {
  const info = isRecord(document) ? document.info : undefined;
  return isRecord(info) && typeof info.title === "string" && info.title !== "" ? info.title : null;
}
