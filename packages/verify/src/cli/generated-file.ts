import { mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { type LockEntry, type WebhooksConfig, readText, writeText } from "./config";
import { GENERATOR_VERSION, generateTypes, readGeneratedHeader } from "./generate";
import { hashText } from "./hash";
import { type RegistryVersion, parseRegistry } from "./registry-client";

export type GeneratedFile = {
  /** `owner/name` */
  registry: string;
  range: string;
  /** Relative to the project root. */
  path: string;
};

/** One file per registry, named after its name part. */
export function generatedFiles(config: WebhooksConfig): GeneratedFile[] {
  const registryByName = new Map<string, string>();
  return Object.entries(config.registries).map(([registry, range]) => {
    const { name } = parseRegistry(registry);
    const path = join(config.out, `${name}.ts`);
    // Lowercased because macOS and Windows file systems ignore case.
    const other = registryByName.get(name.toLowerCase());
    if (other) throw new Error(`${other} and ${registry} would both generate ${path}; keep one of them`);
    registryByName.set(name.toLowerCase(), registry);
    return { registry, range, path };
  });
}

/**
 * Why the file at `path` isn't what this generator writes for the locked
 * version, or null when it is. Lets `pull` skip the registry for current files.
 */
export async function staleReason(
  path: string,
  registry: string,
  locked: LockEntry,
): Promise<string | null> {
  const text = await readText(path);
  if (text === null) return "is missing";
  const header = readGeneratedHeader(text);
  if (
    header === null ||
    header.registry !== registry ||
    header.version !== locked.version ||
    header.documentHash !== locked.hash
  ) {
    return "doesn't match typedhook.lock";
  }
  if (header.generatorVersion !== GENERATOR_VERSION) {
    return `was generated by typedhook generator v${header.generatorVersion}, this one is v${GENERATOR_VERSION}`;
  }
  if ((await hashText(header.body)) !== header.bodyHash) return "was edited by hand";
  return null;
}

export async function writeGeneratedFile(
  path: string,
  registry: string,
  { version, hash, document }: RegistryVersion,
): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await writeText(path, await generateTypes({ registry, version, hash, document }));
}
